/* ============================================================
 *  app_voice —— 语音唤醒与命令词（ESP-SR）
 * ============================================================
 *  设计要点（10-11 第一版）
 *
 *  ① 模型从【独立分区】读，不链进 app：
 *     esp-sr 的 `esp_srmodel_init(分区名)` 走 `srmodel_mmap_init()`
 *     （model_path.c:510-531：找到分区后直接 mmap），读的是
 *     `pack_model.py` 打出来的 **packed 单文件**（不是 SPIFFS 文件系统）。
 *     ⇒ 分区表里有 `model` 分区（partitions.csv，0x710000 / 3 MB），
 *       内容由 `_prep_voice_models.py` 生成、由 `_flash_es28.py voice` 写入。
 *
 *  ② 词表【不】改托管组件：
 *     esp-sr 自带 313 条中文命令词**全是空调/家电**（"打开空调""朝我吹"…），
 *     搜「播放/下一台/音量/暂停」零命中 ⇒ 必须自定义。
 *     而自定义走**运行时 API** `esp_mn_commands_add()`（中文传拼音串），
 *     不碰组件的 `fst/commands_cn.txt` —— 组件重拉不会把词表还原。
 *
 *  ③ 采样率：esp-sr 要 **16 kHz 单声道**；播放是 44.1 kHz 立体声。
 *     而 S3 **没有 ASRC 硬件**、I2S 全双工 TX/RX 共用 BCLK/WS、
 *     ES8311 的 ADC 也只有那一组时钟 ⇒ **录音采样率必然跟随播放采样率**。
 *     兰兰 10-11 定的策略：**暂停/停止时才听**（零音质代价）。
 *     ⇒ `app_voice_start()` 只在"没在放音"时被调用（由播放层保证）。
 *
 *  ⚠️ 本文件目前是【第一版】：只做「挂载模型 + 报告清单」，
 *     用来把 esp-sr 编进固件并确认分区/格式都对。
 *     AFE / WakeNet / MultiNet 在下一步接。
 */
#ifndef APP_VOICE_H
#define APP_VOICE_H

#include <stdbool.h>
#include "esp_err.h"

/* 初始化：挂载 model 分区、列出模型。失败不致命（界面照跑，只是没语音）。*/
esp_err_t app_voice_init(void);

/* 语音链路是否就绪（模型挂上了）。*/
bool app_voice_ready(void);

/* 当前挂载到的模型名（未就绪返回 NULL）—— 给串口调试命令用。*/
const char *app_voice_model_name(int idx);

/* ============================================================
 *  ★ 10-11 批 B：麦克风电平自检（串口 `mic` 命令调它）
 * ============================================================
 *  为什么先做这个而不是直接上 AFE：
 *    语音链路的第一个未知数是【硬件通路到底通不通】——
 *    麦 → ES8311 ADC → I2S RX → 我们读到的数据。这一段没打通的话，
 *    接上 AFE 只会得到"唤醒不了"，而**分不清是麦坏了、还是模型/算法问题**。
 *  ⇒ 先做能给出**数字**的自检：安静时 RMS 应当很小（几十~几百），
 *    对着麦说话/拍手时 RMS 应当明显抬起来（几千以上）。
 *    看这两个数就能判定通路，不需要听、不需要看屏。
 *
 *  ★ 一次跑【两档】采样率，好把"通路问题"和"采样率问题"分开：
 *      档① 当前采样率（一般 44100）—— 证明 ADC 通路本身通
 *      档② 16000 Hz（esp-sr 要的档）—— 证明时钟能切过去
 *    两档都出数 = 硬件侧全部就绪；只有①出数 = 时钟切换有问题。
 *
 *  ⚠️ 调用前必须先把播放停掉（它要独占 codec + I2S 时钟）。
 *  ⚠️ 返回前会把采样率还原成进来时的值，不把播放链路留在 16 kHz。
 *
 *  ms_per_pass：每档采集多少毫秒（建议 1000~2000）。
 */
esp_err_t app_voice_mic_test(int ms_per_pass);

/*  ============================================================
 *  ★ 10-11 批 C：唤醒（AFE + WakeNet）
 *  ============================================================
 *  为什么必须经 AFE（不能把麦数据直接喂 WakeNet）：
 *    AFE 是乐鑫的音频前端，它把「单麦 → 降噪 → 增益归一 → 唤醒」串成一条流水线，
 *    **并且给 WakeNet 的输出是归一化过的**。跳过它直接喂原始麦数据，
 *    唤醒率会明显变差（模型的训练数据就是 AFE 的输出分布）。
 *
 *  数据流（本模块）：
 *    ES8311 ADC → I2S RX（16 kHz **立体声交错**，麦在左声道）
 *      → 取出左声道 → 单声道 int16 → AFE.feed()
 *      → AFE.fetch() 的 wakeup_state == WAKENET_DETECTED ⇒ 唤醒！
 *
 *  ⚠️ 三条硬约束：
 *    ① **采样率必须是 16 kHz**：AFE 按 `get_samp_rate()` 跑，而我们的 I2S
 *       采样率由时钟决定（TX/RX 共用）⇒ 开听之前必须先
 *       `app_audio_set_sample_rate(16000)`，且**期间不能放音**（会互相改钟）。
 *       本模块自己负责这两步（start 里切钟、stop 里还原）。
 *    ② **feedsize 由 AFE 决定**，不是随便给：`get_samp_chunksize()` 给多少，
 *       每轮就要喂「chunksize 个样本（单声道）」。喂错大小会让它内部错位，
 *       症状是「一直不唤醒」而**不报错**。
 *    ③ 内部 RAM 紧张（空闲约 177 KB）⇒ 配置用
 *       `AFE_MEMORY_ALLOC_MORE_PSRAM`，把大缓冲放 PSRAM。*/
esp_err_t app_voice_start(void);
esp_err_t app_voice_stop(void);
bool      app_voice_is_running(void);

/* 累计唤醒次数（验证用：喊几次就该涨几次）。*/
int       app_voice_wake_count(void);

#endif /* APP_VOICE_H */
